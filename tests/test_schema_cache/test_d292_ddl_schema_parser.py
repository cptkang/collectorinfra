def _columns(result: Any, table: str) -> dict[str, tuple[str, bool, bool, str | None]]:
    return {
        c.name: (c.data_type, c.nullable, c.is_primary_key, c.references)
        for c in result.schema.tables[table].columns
    }


def _snapshot_of(schema: Any) -> tuple[dict[str, Any], dict[str, Any]]:
    schema_dict, table_schemas = schema_dict_from_full_schema(schema)
    return schema_dict, build_snapshot(schema_dict, table_schemas)


