async def _mcp_snapshot(engine: str, tables: dict[str, FakeTable]) -> tuple[dict, dict]:
    session = FakeMCPSession()
    session.add_source("app_src", engine, tables)
    async with client_factory(session)("app_src") as client:
        return _snapshot_of(await client.get_full_schema())


def _table(columns: list[tuple[str, str, bool, bool]], fks=(), schema: str = "public") -> FakeTable:
    return FakeTable(list(columns), list(fks), schema)


@pytest.mark.parametrize(
    ("engine", "ddl", "mcp_tables"),
    [
        pytest.param("postgresql", PG_DUMP, {
            "t_node": _table([
                ("id", "integer", False, True), ("parent_id", "integer", True, False),
                ("node_type", "character varying", True, False),
                ("created", "timestamp without time zone", True, False),
                ("tags", "ARRAY", True, False), ("mood", "USER-DEFINED", True, False),
                ("amount", "numeric", True, False),
            ]),
            "t_asset": _table(
                [("id", "bigint", False, True), ("node_id", "integer", True, False),
                 ("ok", "boolean", True, False)],
                fks=[("node_id", "t_node", "id")],
            ),
            "ops.t_log": _table(
                [("seq", "bigint", False, True), ("body", "text", True, False)], schema="ops"
            ),
        }, id="postgresql"),
        pytest.param("db2", DB2_LOOK, {
            "T_NODE": _table([
                ("ID", "BIGINT", False, True), ("NAME", "VARCHAR", True, False),
                ("FLAG", "CHARACTER", False, False), ("TS", "TIMESTAMP", False, False),
                ("AMT", "DECIMAL", True, False),
            ], schema="APP"),
            "T_CHILD": _table(
                [("ID", "INTEGER", False, True), ("NODE_ID", "BIGINT", True, False)],
                fks=[("NODE_ID", "T_NODE", "ID")], schema="APP",
            ),
        }, id="db2"),
        pytest.param("mariadb", MARIADB_DUMP, {
            "t_item": _table([
                ("id", "int", False, True), ("name", "varchar", True, False),
                ("owner_id", "bigint", True, False), ("payload", "longtext", True, False),
                ("flag", "tinyint", False, False),
            ], fks=[("owner_id", "t_owner", "id")], schema="app"),
            "t_owner": _table([("id", "bigint", False, True)], schema="app"),
        }, id="mariadb"),
    ],
)
async def test_ddl_snapshot_hash_equals_mcp_collection(engine, ddl, mcp_tables):
    """같은 구조면 DDL 해석 스냅샷 = MCP 수집 스냅샷(해시·관계) — 이후 MCP 점검에 가짜 차이 0."""
    mcp_dict, mcp_snapshot = await _mcp_snapshot(engine, mcp_tables)
    ddl_dict, ddl_snapshot = _snapshot_of(parse_ddl(ddl, engine).schema)

    assert ddl_snapshot["hash"] == mcp_snapshot["hash"]
    assert sorted(ddl_snapshot["tables"]) == sorted(mcp_snapshot["tables"])
    assert ddl_dict["relationships"] == mcp_dict["relationships"]
