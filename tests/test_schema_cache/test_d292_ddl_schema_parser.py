"""D-292 — DDL 해석기(`parse_ddl`): 엔진별 덤프 형식 · 경고 · MCP 수집과의 스냅샷 동등성.

핵심 계약: 같은 구조라면 DDL 해석 결과의 스냅샷 해시가 MCP `get_full_schema` 수집 결과와 같다 —
그래야 DDL로 등록한 기준선을 뒤에 MCP로 변경 점검해도 가짜 차이가 나지 않는다. MCP 쪽은 실제
`DBHubClient`에 가짜 세션을 붙여(서비스 테스트 공용 픽스처) 엔진별 MCP 서버 응답 표기
(`information_schema.data_type` · DB2 `TYPENAME` · bare 키 규칙)를 흉내 낸다.

이름은 전부 가상(`app_*`·`t_*`) — 운영 스키마 리터럴을 쓰지 않는다. 네트워크·Redis·LLM 0.
"""

