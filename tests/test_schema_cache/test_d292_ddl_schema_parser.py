class TestPostgres:
    def test_pg_dump_tables_types_keys(self):
        result = parse_ddl(PG_DUMP, "postgresql")

        assert list(result.schema.tables) == ["t_node", "t_asset", "ops.t_log"]
        assert result.schema.tables["t_node"].schema_name == "public"
        assert result.schema.tables["ops.t_log"].schema_name == "ops"
        assert _columns(result, "t_node") == {
            "id": ("integer", False, True, None),  # PK는 NOT NULL
            "parent_id": ("integer", True, False, None),
            "node_type": ("character varying", True, False, None),
            "created": ("timestamp without time zone", True, False, None),
            "tags": ("ARRAY", True, False, None),
            "mood": ("USER-DEFINED", True, False, None),
            "amount": ("numeric", True, False, None),  # CHECK 안의 NOT NULL은 속성이 아니다
        }
        assert _columns(result, "t_asset")["node_id"] == ("integer", True, False, "t_node.id")
        assert result.schema.relationships == [{"from": "t_asset.node_id", "to": "t_node.id"}]
        assert result.warnings == []

    def test_pg_dump_comments_and_skipped_statements(self):
        result = parse_ddl(PG_DUMP, "postgresql")

        assert result.comments == {"t_node": "노드", "t_node.node_type": "노드 유형"}
        assert result.skipped == {
            "SET": 1, "SELECT": 1, "CREATE FUNCTION": 1, "CREATE TYPE": 1, "CREATE INDEX": 1,
            "ALTER TABLE (그 밖의 변경)": 1, "CREATE TEMPORARY TABLE": 1, "CREATE VIEW": 1,
        }
        # 함수 본문(달러 인용)의 `;`가 문장을 자르지 않는다 — 문장 17개(본문 `;`까지 세면 19)
        assert result.statement_count == 17

    def test_unquoted_identifiers_fold_to_lower(self):
        ddl = 'CREATE TABLE T_Up (Id INT PRIMARY KEY, "MixedCase" TEXT);'
        result = parse_ddl(ddl, "postgresql")

        assert list(result.schema.tables) == ["t_up"]
        assert [c.name for c in result.schema.tables["t_up"].columns] == ["id", "MixedCase"]


class TestDB2:
    def test_db2look_padded_schema_upper_types_and_fk_to_pk(self):
        result = parse_ddl(DB2_LOOK, "db2")

        assert list(result.schema.tables) == ["T_NODE", "T_CHILD"]  # DB2 키는 항상 bare
        # db2look의 8자 채움 스키마명은 MCP(`TRIM(TABSCHEMA)`)처럼 뒤 공백을 뗀다
        assert result.schema.tables["T_NODE"].schema_name == "APP"
        assert result.schema.tables["T_CHILD"].schema_name == "APP"
        assert _columns(result, "T_NODE") == {
            "ID": ("BIGINT", False, True, None),
            "NAME": ("VARCHAR", True, False, None),
            "FLAG": ("CHARACTER", False, False, None),
            "TS": ("TIMESTAMP", False, False, None),
            "AMT": ("DECIMAL", True, False, None),
        }
        # 대상 컬럼이 없는 REFERENCES는 대상 PK로 푼다
        assert _columns(result, "T_CHILD")["NODE_ID"] == ("BIGINT", True, False, "T_NODE.ID")
        assert result.schema.relationships == [{"from": "T_CHILD.NODE_ID", "to": "T_NODE.ID"}]
        assert result.warnings == []

    def test_db2_comments_terminator_and_skipped(self):
        result = parse_ddl(DB2_LOOK, "db2")

        assert result.comments == {"T_NODE.NAME": "이름", "T_CHILD.NODE_ID": "노드"}
        # `--#SET TERMINATOR @` 뒤 트리거 본문의 `;`는 문장 끝이 아니다
        assert result.skipped == {"CONNECT": 1, "CREATE TRIGGER": 1}

    def test_default_schema_fills_unqualified_tables(self):
        result = parse_ddl("CREATE TABLE T_A (ID INT NOT NULL);", "db2", default_schema="APPS")

        assert result.schema.tables["T_A"].schema_name == "APPS"


class TestMariaDB:
    def test_mysqldump_backticks_types_comments(self):
        result = parse_ddl(MARIADB_DUMP, "mariadb")

        assert list(result.schema.tables) == ["t_item", "t_owner"]
        assert _columns(result, "t_item") == {
            "id": ("int", False, True, None),  # unsigned·AUTO_INCREMENT는 타입 표기에 넣지 않는다
            "name": ("varchar", True, False, None),
            "owner_id": ("bigint", True, False, "t_owner.id"),
            "payload": ("longtext", True, False, None),  # MariaDB JSON = LONGTEXT 별칭
            "flag": ("tinyint", False, False, None),
        }
        assert _columns(result, "t_owner") == {"id": ("bigint", False, True, None)}
        assert result.comments == {
            "t_item.id": "아이디", "t_item.name": "it's", "t_item": "항목 # 주석 아님",
        }
        assert result.skipped == {"DROP TABLE": 1, "INSERT": 1, "CREATE TRIGGER": 1}
        assert result.warnings == []

    def test_qualifier_against_default_database(self):
        ddl = "CREATE TABLE app.t_a (id INT); CREATE TABLE other.t_b (id INT);"

        assert list(parse_ddl(ddl, "mariadb", default_schema="app").schema.tables) == [
            "t_a", "other.t_b",
        ]
        # 기본 database를 모르면 한정자를 무시한다(덤프 하나 = database 하나)
        assert list(parse_ddl(ddl, "mariadb").schema.tables) == ["t_a", "t_b"]


