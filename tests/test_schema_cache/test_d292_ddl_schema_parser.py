class TestWarnings:
    def test_unreadable_definitions_are_reported(self):
        ddl = """
        CREATE TABLE t_copy AS SELECT * FROM t_src;
        CREATE TABLE t_like (LIKE t_src INCLUDING ALL);
        CREATE TABLE t_a (id int PRIMARY KEY, b_id int REFERENCES t_missing(id));
        ALTER TABLE t_unknown ADD CONSTRAINT pk PRIMARY KEY (id);
        """
        result = parse_ddl(ddl, "postgresql")

        assert list(result.schema.tables) == ["t_a"]  # 컬럼 없는 t_like는 등록에서 뺀다
        assert any("열 목록이 없는 CREATE TABLE" in w and "t_copy" in w for w in result.warnings)
        assert any("LIKE" in w and "t_like" in w for w in result.warnings)
        assert any("컬럼을 하나도 읽지 못한" in w and "t_like" in w for w in result.warnings)
        assert any("정의되지 않은 테이블" in w and "t_unknown" in w for w in result.warnings)
        assert any("참조 대상 테이블이 DDL에 없습니다" in w for w in result.warnings)
        # 대상이 DDL에 없어도 대상 컬럼이 명시되면 MCP처럼 관계는 남긴다
        assert result.schema.relationships == [{"from": "t_a.b_id", "to": "t_missing.id"}]

    def test_alter_add_column_and_redefinition(self):
        ddl = """
        CREATE TABLE t_a (id int);
        ALTER TABLE t_a ADD COLUMN note varchar(10) NOT NULL, ADD PRIMARY KEY (id);
        CREATE TABLE t_b (x int);
        CREATE TABLE t_b (y int);
        """
        result = parse_ddl(ddl, "postgresql")

        assert _columns(result, "t_a") == {
            "id": ("integer", False, True, None),
            "note": ("character varying", False, False, None),
        }
        assert [c.name for c in result.schema.tables["t_b"].columns] == ["y"]
        assert any("다시 정의" in w and "t_b" in w for w in result.warnings)

    def test_warning_list_is_capped(self):
        ddl = "\n".join(f"ALTER TABLE t_{i} ADD PRIMARY KEY (id);" for i in range(MAX_WARNINGS + 5))
        result = parse_ddl(ddl, "postgresql")

        assert len(result.warnings) == MAX_WARNINGS + 1
        assert result.warnings[-1] == "… 외 경고 5건"

    def test_unsupported_engine(self):
        with pytest.raises(ValueError, match="engine"):
            parse_ddl("CREATE TABLE t (id int);", "oracle")

    def test_strings_and_comments_do_not_split_statements(self):
        statements = split_statements(
            "CREATE TABLE t (a varchar(3) DEFAULT ';'); -- ; 주석\n/* ; */ SELECT 1;", "postgresql"
        )

        assert len(statements) == 2


